export function validateBurgerCatalog(catalog: BurgerRecord[]) {
  const errors: string[] = []
  const seenSlugs = new Set<string>()
  const seenArchiveNumbers = new Set<string>()

  for (const burger of catalog) {
    if (seenSlugs.has(burger.slug)) errors.push(`重复 slug: ${burger.slug}`)
    if (seenArchiveNumbers.has(burger.archiveNo)) errors.push(`重复档案编号: ${burger.archiveNo}`)
    if (!/^\d{3}$/.test(burger.archiveNo)) errors.push(`无效档案编号: ${burger.archiveNo}`)
    if (burger.components.length < 4) errors.push(`配料层次不足: ${burger.slug}`)
    if (burger.flavors.length < 2) errors.push(`风味标签不足: ${burger.slug}`)
    if (!burger.name || !burger.country || !burger.countryCode) errors.push(`基础信息缺失: ${burger.slug}`)
    if (!burger.reference.label || !/^https:\/\//.test(burger.reference.url)) {
      errors.push(`无效资料链接: ${burger.slug}`)
    }

    seenSlugs.add(burger.slug)
    seenArchiveNumbers.add(burger.archiveNo)
  }

  return errors
}

const catalogErrors = validateBurgerCatalog(burgers)

if (catalogErrors.length > 0) {
  throw new Error(`汉堡档案数据校验失败:\n${catalogErrors.join('\n')}`)
}

