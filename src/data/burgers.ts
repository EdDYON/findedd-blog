function createWorldVisual(recipe: BurgerVisualRecipe): BurgerVisual {
  const [bun, bunShade] = bunPalettes[recipe.bunStyle]

  return {
    ...recipe,
    bun,
    bunShade,
    main: mainColors[recipe.mainStyle],
    cheese: cheeseColors[recipe.cheeseStyle],
    greens: freshColors[recipe.freshStyle],
    sauce: sauceColors[recipe.sauceStyle],
    accent: accentColors[recipe.freshStyle] ?? sauceColors[recipe.sauceStyle],
  }
}

